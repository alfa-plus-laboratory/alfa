/**
 * 干活的那个小机器人。
 *
 * ── 为什么不是一个转圈 ──
 * 那个 ⠹ 只说了一件事:程序还活着。可等待期间用户真正想知道的是**它在干嘛** ——
 * 在想、在动手、还是在等我点头。三种状态在转圈上长得一模一样,于是那几十秒里
 * 屏幕上唯一在动的东西,一个字的信息量都没有。
 *
 * 机器人把这件事演出来:想的时候脸上的扫描条来回扫,动手的时候抡胳膊,
 * 说话的时候脸变成一条声波,轮到你的时候脸上是个问号。**动作本身就是状态**,
 * 不用去读字。
 *
 * ── 他只住在最底下那一行 ──
 * 一度还有一只三行的整机器人站在活动区里。撤掉了:那片地方是留给**它在想
 * 什么**的 —— 思考过程直接铺在那儿比一个再好看的动画有用得多。会动的东西
 * 留一个就够,多一个只是在和正文抢眼睛。
 *
 * ── 三条硬规矩 ──
 * ① **每一格都等宽**。他后面还跟着 `bash · 12.4s · esc to interrupt`,宽度只要
 *    抖一格,后面整串字就跟着左右跳 —— 一行会自己扭动的状态栏比没有动画更难看。
 *    所以所有姿势都补齐到 MASCOT_WIDTH,空位用空格占着。
 * ② **只用界面本来就在用的那类字符**。方块和制表符(`▛ ▀ ● ─`)和大框
 *    `╭─┬╮` 是同一类:东亚宽度里都算 Ambiguous,而这个界面从第一天起就假定
 *    它们占一列。不引入 emoji —— 那是另一个宽度类,一旦算错就换行啃输出。
 * ③ **不做成开关**。要调就改这里的常量 —— 一个"动画风格"设置项的维护成本
 *    远高于它带来的乐趣。
 */

/** 每一帧都占这么多列 */
export const MASCOT_WIDTH = 7

/**
 * 这一行窄到这个宽度以下就别放他了,换回一个字的转圈。
 *
 * 他要占七列,而同一行上还有「怎么停下来」那句提示 —— 挤的时候字优先:
 * 一个看着热闹但读不到 `esc to interrupt` 的状态行,是拿出路换了个乐子。
 */
export const MASCOT_MIN_WIDTH = MASCOT_WIDTH + 29

/** 他现在在干嘛。判定在 chat.ts 那边做 —— 那里才看得见模型和看板的状态 */
export type Mood = "idle" | "think" | "work" | "talk" | "wait"

interface Act {
  /** 一帧撑几个 tick(一个 tick = SPINNER_MS = 100ms) */
  hold: number
  /** 脸上那块显示屏,**三格** */
  face: readonly string[]
  /** 左右胳膊,一帧两个字符:左、右 */
  arms: readonly string[]
}

/**
 * 两个通道**各转各的周期**(face 四帧、arms 两帧也行),按同一个帧号各自
 * 取模 —— 全部对齐反而像个节拍器。
 */
const CAST: Record<Mood, Act> = {
  /**
   * 歇着:**一动不动**,而且是故意的。
   *
   * ① 没有东西在跑,就不该有东西在动 —— 这一整套动画的前提是「动 = 正在发生」,
   *   空闲时还在挥手的话,那个前提就废了,用户再也不能靠眼角判断它忙不忙。
   * ② 就算想让他动也动不了:计时器只在 busy 时跑(app.ts 的 startTimer),
   *   空闲时 tick 根本不往前走 —— 写成多帧的结果是他卡在第一帧,那是个
   *   看着像坏了的"动画"。
   *
   * 上色也退成 dim(见 chat.ts 的 busyGlyph):他还在那儿,但没在替你干活。
   */
  idle: { hold: 1, face: ["● ●"], arms: ["──"] },
  /**
   * 想:脸上一条扫描条来回扫。
   *
   * 模型想了四十秒的时候,屏幕上什么都没有 —— 那片空地上必须有个东西在动,
   * 否则它和卡死长得一模一样。
   */
  think: { hold: 2, face: ["▮  ", " ▮ ", "  ▮", " ▮ "], arms: ["──"] },
  /**
   * 干活:眼睛亮着,胳膊上下抡。
   *
   * 扫描条停下来是重点 —— 「他不扫了,开始动手了」这件事眼角余光就能看见,
   * 而工具名还得低头去读。
   */
  work: { hold: 2, face: ["● ●"], arms: ["╱╲", "──", "╲╱", "──"] },
  /**
   * 说话:脸变成一条声波。
   *
   * 正文这时候正一行行长在他上面,动作跟着它走。
   */
  talk: { hold: 3, face: ["▁▂▁", "▃▅▃", "▅█▅", "▃▅▃"], arms: ["──"] },
  /**
   * 等你:脸上的眼睛和问号交替闪。
   *
   * 这一格必须和前三种**一眼分得开** —— 它不是"还得等",是"卡在你身上了"。
   * 颜色那边也一起换成黄色(见 chat.ts 的 busyGlyph)。
   */
  wait: { hold: 5, face: ["● ●", " ? "], arms: ["──"] },
}

/**
 * 状态行上那张脸:`─[● ●]─`。
 *
 * 纯函数,不自己计时 —— 计时器在 app.ts 只有一个,多一个就会出现两处动画
 * 各跑各的,而它们画在同一行里。
 */
export function mascot(mood: Mood, tick: number): string {
  const { face, arms } = pose(mood, tick)
  return `${arms[0]}[${face}]${arms[1]}`
}

function pose(mood: Mood, tick: number): { face: string; arms: string } {
  const act = CAST[mood]
  const frame = Math.floor(Math.max(0, tick) / act.hold)
  const at = <T>(channel: readonly T[]): T => channel[frame % channel.length]!
  return { face: at(act.face), arms: at(act.arms) }
}
